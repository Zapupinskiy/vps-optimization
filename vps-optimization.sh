#!/usr/bin/env bash
# Personal Ubuntu 24.04 setup. No telemetry, agents or remote self-updates.
set -Eeuo pipefail
umask 077
SSH_KEY='ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIOZTi0QLLLpfWCEtDB2rIcIyMUXGdHvylhtbW5xwEtC0 Generated By Termius'
SSH_PORT=1679
HOST_NAME=''
INSTALL_DOCKER=true
usage() {
  echo "Usage: sudo bash $0 [--hostname NAME] [--ssh-port PORT] [--no-docker]"
}
while (($#)); do
  case "$1" in
    --hostname) [[ $# -ge 2 ]] || { usage; exit 2; }; HOST_NAME=$2; shift 2 ;;
    --ssh-port) [[ $# -ge 2 ]] || { usage; exit 2; }; SSH_PORT=$2; shift 2 ;;
    --no-docker) INSTALL_DOCKER=false; shift ;;
    --help|-h) usage; exit 0 ;;
    *) usage; exit 2 ;;
  esac
done
[[ $EUID -eq 0 ]] || { echo 'Run as root.' >&2; exit 1; }
. /etc/os-release
[[ $ID == ubuntu && $VERSION_ID == 24.04 ]] || { echo 'Ubuntu 24.04 is required.' >&2; exit 1; }
[[ $SSH_PORT =~ ^[0-9]{1,5}$ ]] && ((10#$SSH_PORT >= 1 && 10#$SSH_PORT <= 65535)) || { echo 'Invalid SSH port.' >&2; exit 2; }
SSH_PORT=$((10#$SSH_PORT))
[[ -z $HOST_NAME || ( ${#HOST_NAME} -le 63 && $HOST_NAME =~ ^[a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?$ ) ]] || { echo 'Invalid hostname.' >&2; exit 2; }
# Refuse to alter an already deployed host: firewall/SSH changes need separate review.
if command -v docker >/dev/null && [[ -n $(docker ps -q 2>/dev/null) ]]; then
  echo 'Running Docker containers detected. Use this installer on a fresh server.' >&2
  exit 1
fi
BACKUP=/root/server-setup-backup/$(date -u +%Y%m%dT%H%M%SZ)
mkdir -p "$BACKUP"
for f in /etc/ssh/sshd_config /etc/fstab /etc/hostname /etc/hosts /etc/ufw/user.rules /etc/ufw/user6.rules; do
  [[ ! -f $f ]] || cp --parents -a "$f" "$BACKUP/"
done
mkdir -p /var/log
exec > >(tee -a /var/log/server-setup.log) 2>&1
trap 'echo "Setup failed at line $LINENO. Backups: $BACKUP" >&2' ERR
export DEBIAN_FRONTEND=noninteractive
apt-get update
apt-get install -y ca-certificates curl gnupg python3 openssh-server ufw fail2ban unattended-upgrades apt-listchanges
apt-get upgrade -y
[[ -z $HOST_NAME ]] || hostnamectl set-hostname "$HOST_NAME"
timedatectl set-timezone Europe/Moscow
# Preserve existing authorized keys; add only the public key supplied by the owner.
install -d -m 700 /root/.ssh
touch /root/.ssh/authorized_keys
chmod 600 /root/.ssh/authorized_keys
key_file=$(mktemp)
printf '%s\n' "$SSH_KEY" > "$key_file"
ssh-keygen -lf "$key_file" >/dev/null
rm -f "$key_file"
grep -qxF "$SSH_KEY" /root/.ssh/authorized_keys || printf '%s\n' "$SSH_KEY" >> /root/.ssh/authorized_keys
# Keep the existing SSH ports until the new connection has been verified.
mkdir -p /etc/ssh/sshd_config.d /run/sshd
sshd -T > "$BACKUP/sshd-effective-before.txt"
mapfile -t OLD_PORTS < <(awk '$1=="port" {print $2}' "$BACKUP/sshd-effective-before.txt")
ufw allow "$SSH_PORT/tcp"
for port in "${OLD_PORTS[@]}"; do ufw allow "$port/tcp"; done
cat > /etc/ssh/sshd_config.d/00-personal-setup.conf <<EOF
Port $SSH_PORT
PubkeyAuthentication yes
PasswordAuthentication no
KbdInteractiveAuthentication no
PermitRootLogin prohibit-password
MaxAuthTries 4
EOF
sshd -t
# Check effective policy before activating it (cloud images can have other includes).
sshd -T > "$BACKUP/sshd-effective-after.txt"
grep -qx 'passwordauthentication no' "$BACKUP/sshd-effective-after.txt"
grep -qx 'pubkeyauthentication yes' "$BACKUP/sshd-effective-after.txt"
if systemctl is-active --quiet ssh.socket; then
  mkdir -p /etc/systemd/system/ssh.socket.d
  {
    echo '[Socket]'
    echo 'ListenStream='
    printf 'ListenStream=%s\n' "$SSH_PORT" "${OLD_PORTS[@]}" | sort -u
  } > /etc/systemd/system/ssh.socket.d/10-personal-ports.conf
  systemctl daemon-reload
  systemctl restart ssh.socket
fi
systemctl reload-or-restart ssh
# Create a 2 GiB swap file only if no swap is active. Standard ext4/xfs images only.
if [[ $(swapon --noheadings --show | wc -l) -eq 0 ]]; then
  fs=$(findmnt -n -o FSTYPE /)
  if [[ $fs == ext4 || $fs == xfs ]]; then
    if [[ ! -e /swapfile ]]; then
      available=$(df --output=avail -k / | tail -1)
      ((available > 3145728)) || { echo 'Insufficient disk space for swap.' >&2; exit 1; }
      dd if=/dev/zero of=/swapfile bs=1M count=2048 status=none
      chmod 600 /swapfile
      mkswap /swapfile
    fi
    # Never reformat an existing file.
    swapon /swapfile
    grep -qE '^/swapfile[[:space:]]' /etc/fstab || echo '/swapfile none swap sw 0 0' >> /etc/fstab
  else
    echo "Swap creation skipped for filesystem $fs."
  fi
fi
mkdir -p /etc/systemd/journald.conf.d
cat > /etc/systemd/journald.conf.d/90-personal-limits.conf <<'EOF'
[Journal]
SystemMaxUse=200M
RuntimeMaxUse=50M
MaxRetentionSec=14day
EOF
systemctl restart systemd-journald
cat > /etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
EOF
cat > /etc/apt/apt.conf.d/52personal-no-reboot <<'EOF'
Unattended-Upgrade::Automatic-Reboot "false";
EOF
cat > /etc/fail2ban/jail.d/personal-sshd.local <<EOF
[sshd]
enabled = true
backend = systemd
port = $SSH_PORT,$(IFS=,; echo "${OLD_PORTS[*]}")
maxretry = 6
findtime = 10m
bantime = 1h
EOF
systemctl enable --now fail2ban
systemctl restart fail2ban
if $INSTALL_DOCKER; then
  install -m 0755 -d /etc/apt/keyrings
  curl --fail --silent --show-error --location --proto '=https' --tlsv1.2 https://download.docker.com/linux/ubuntu/gpg -o /etc/apt/keyrings/docker.asc
  # Check the repository signing key before trusting it.
  fingerprint=$(gpg --show-keys --with-colons /etc/apt/keyrings/docker.asc | awk -F: '$1=="fpr" {print $10; exit}')
  [[ $fingerprint == 9DC858229FC7DD38854AE2D88D81803C0EBFCD88 ]]
  chmod a+r /etc/apt/keyrings/docker.asc
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/ubuntu noble stable" > /etc/apt/sources.list.d/docker.list
  apt-get update
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
  mkdir -p /etc/docker
  # Keep existing settings; Docker is allowed to validate the merged JSON.
  python3 - <<'PYDOCKER'
import json,pathlib
p=pathlib.Path('/etc/docker/daemon.json')
c=json.loads(p.read_text()) if p.exists() else {}
c.setdefault('log-driver','local')
if c['log-driver']=='local':
    c.setdefault('log-opts',{}).update({'max-size':'10m','max-file':'3'})
p.write_text(json.dumps(c,indent=2)+'\n')
PYDOCKER
  dockerd --validate --config-file=/etc/docker/daemon.json
  systemctl enable docker
  systemctl restart docker
  docker compose version
fi
ufw default deny incoming
ufw default allow outgoing
ufw allow 80/tcp
ufw allow 443/tcp
ufw --force enable
ufw status
sshd -t
systemctl is-active ssh fail2ban
apt-get clean
echo "Setup completed. SSH port: $SSH_PORT. Existing SSH ports preserved."
echo 'Open a SECOND SSH session with your key before closing the current session.'
echo "Backups: $BACKUP; local log: /var/log/server-setup.log"
if [[ -f /var/run/reboot-required ]]; then echo 'A reboot is required. Reboot manually after checking SSH.'; fi
