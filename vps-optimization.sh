
#!/usr/bin/env bash
# Universal Ubuntu VPS optimization
# SSH port: 1679
# Automatic setup without questions
# UFW is NOT enabled automatically

set -Eeuo pipefail
umask 077

LOG="/var/log/vps-optimization.log"
exec > >(tee -a "$LOG") 2>&1

say() { printf '\n[%s] %s\n' "$(date '+%F %T')" "$*"; }
warn() { printf '[WARNING] %s\n' "$*" >&2; }
die() { printf '[ERROR] %s\n' "$*" >&2; exit 1; }

[[ $EUID -eq 0 ]] || die "Run as root."
command -v apt-get >/dev/null || die "Ubuntu/Debian with apt required."

. /etc/os-release
[[ "${ID:-}" == "ubuntu" || "${ID_LIKE:-}" == *debian* ]] || die "Unsupported OS."

SSH_PORT=1679
SSH_PUBLIC_KEY='ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIOZTi0QLLLpfWCEtDB2rIcIyMUXGdHvylhtbW5xwEtC0 Generated By Termius'

STAMP=$(date +%Y%m%d-%H%M%S)
BACKUP="/root/vps-optimization-backup-$STAMP"
mkdir -p "$BACKUP"

backup() {
    local file="$1"
    if [[ -e "$file" ]]; then
        mkdir -p "$BACKUP$(dirname "$file")"
        cp -a "$file" "$BACKUP$file"
    fi
}

say "Server information"
echo "OS: ${PRETTY_NAME:-unknown}"
echo "Kernel: $(uname -r)"
echo "CPU: $(nproc)"
free -h
df -h /

say "Installing basic packages"

export DEBIAN_FRONTEND=noninteractive

apt-get update
apt-get install -y --no-install-recommends \
    ca-certificates curl jq unattended-upgrades fail2ban ufw

say "TCP optimization"

SYSCTL="/etc/sysctl.d/99-vps-baseline.conf"
backup "$SYSCTL"

cat > "$SYSCTL" <<'EOF'
fs.file-max = 1048576
net.core.somaxconn = 2048
net.ipv4.tcp_syncookies = 1
net.ipv4.tcp_fin_timeout = 20
net.ipv4.tcp_keepalive_time = 600
net.ipv4.tcp_keepalive_intvl = 30
net.ipv4.tcp_keepalive_probes = 5
net.ipv4.ip_local_port_range = 10240 65535
vm.swappiness = 10
EOF

CC=$(sysctl -n net.ipv4.tcp_available_congestion_control 2>/dev/null || true)

if grep -qw bbr <<< "$CC"; then
    cat >> "$SYSCTL" <<'EOF'
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = bbr
EOF
    say "BBR enabled."
else
    say "BBR unavailable. Keeping default congestion control."
fi

sysctl --system

say "System limits"

LIMITS="/etc/security/limits.d/99-vps-baseline.conf"
backup "$LIMITS"

cat > "$LIMITS" <<'EOF'
* soft nofile 65535
* hard nofile 65535
root soft nofile 65535
root hard nofile 65535
EOF

mkdir -p /etc/systemd/system.conf.d

SDROP="/etc/systemd/system.conf.d/99-vps-baseline.conf"
backup "$SDROP"

cat > "$SDROP" <<'EOF'
[Manager]
DefaultLimitNOFILE=65535
EOF

systemctl daemon-reexec

say "System journal limits"

mkdir -p /etc/systemd/journald.conf.d

JOURNAL="/etc/systemd/journald.conf.d/99-vps-baseline.conf"
backup "$JOURNAL"

cat > "$JOURNAL" <<'EOF'
[Journal]
SystemMaxUse=500M
SystemMaxFileSize=50M
MaxRetentionSec=14day
EOF

systemctl restart systemd-journald

say "Fail2ban configuration"

mkdir -p /etc/fail2ban/jail.d

JAIL="/etc/fail2ban/jail.d/99-vps-sshd.local"
backup "$JAIL"

cat > "$JAIL" <<'EOF'
[sshd]
enabled = true
backend = systemd
maxretry = 5
findtime = 10m
bantime = 1h
EOF

systemctl enable --now fail2ban
systemctl restart fail2ban

say "Automatic security updates"

AUTO="/etc/apt/apt.conf.d/20auto-upgrades"
backup "$AUTO"

cat > "$AUTO" <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::AutocleanInterval "7";
EOF

systemctl enable --now unattended-upgrades 2>/dev/null || true

say "Swap configuration"

if ! swapon --show --noheadings | grep -q .; then
    RAM_KB=$(awk '/MemTotal:/ {print $2}' /proc/meminfo)
    FREE_KB=$(df -Pk / | awk 'NR==2 {print $4}')

    if (( RAM_KB <= 2097152 && FREE_KB >= 2097152 )); then
        if ! fallocate -l 1G /swapfile 2>/dev/null; then
            dd if=/dev/zero of=/swapfile bs=1M count=1024 status=none
        fi

        chmod 600 /swapfile
        mkswap /swapfile
        swapon /swapfile

        grep -qE '^/swapfile[[:space:]]' /etc/fstab || \
            echo '/swapfile none swap sw 0 0' >> /etc/fstab

        say "Created 1 GB swap."
    else
        say "Swap not required."
    fi
else
    say "Existing swap detected. No changes."
fi

say "SSH configuration"

mkdir -p /root/.ssh
chmod 700 /root/.ssh

touch /root/.ssh/authorized_keys
chmod 600 /root/.ssh/authorized_keys

grep -qxF "$SSH_PUBLIC_KEY" /root/.ssh/authorized_keys || \
    printf '%s\n' "$SSH_PUBLIC_KEY" >> /root/.ssh/authorized_keys

backup /etc/ssh/sshd_config

mkdir -p /etc/ssh/sshd_config.d

DROPIN="/etc/ssh/sshd_config.d/00-vps-optimization.conf"

# Back up all existing SSH configuration files.
while IFS= read -r -d '' cfg; do
    backup "$cfg"
done < <(find /etc/ssh -maxdepth 2 -type f \
    \( -name 'sshd_config' -o -path '/etc/ssh/sshd_config.d/*.conf' \) -print0)

# Remove old Port directives to prevent multiple listeners.
while IFS= read -r -d '' cfg; do
    [[ "$cfg" == "$DROPIN" ]] && continue

    sed -i -E \
        's/^([[:space:]]*)Port([[:space:]]+)/# managed by vps-optimization: Port\2/' \
        "$cfg"
done < <(find /etc/ssh -maxdepth 2 -type f \
    \( -name 'sshd_config' -o -path '/etc/ssh/sshd_config.d/*.conf' \) -print0)

backup "$DROPIN"

cat > "$DROPIN" <<EOF
Port $SSH_PORT
PubkeyAuthentication yes
PasswordAuthentication yes
PermitRootLogin yes
EOF

if ! sshd -t; then
    die "SSH configuration validation failed. Check backup: $BACKUP"
fi

say "Allowing SSH port before restarting"

ufw allow "${SSH_PORT}/tcp" comment 'SSH port 1679' || true

say "Disabling systemd SSH socket activation"

# Critical fix for Ubuntu 24.04:
# ssh.socket can keep SSH listening on port 22.
systemctl disable --now ssh.socket 2>/dev/null || true

say "Enabling regular SSH service"

systemctl enable ssh.service

if ! systemctl restart ssh.service; then
    warn "SSH restart failed. Restoring SSH configuration."

    cp -a "$BACKUP/etc/ssh/sshd_config" /etc/ssh/sshd_config

    if [[ -d "$BACKUP/etc/ssh/sshd_config.d" ]]; then
        cp -a "$BACKUP/etc/ssh/sshd_config.d/." /etc/ssh/sshd_config.d/
    fi

    systemctl restart ssh.service || true
    die "SSH restart failed. Do not close your current session."
fi

sleep 2

if ! ss -lntp | grep -qE "0\.0\.0\.0:${SSH_PORT}[[:space:]]|\[::\]:${SSH_PORT}[[:space:]]"; then
    warn "SSH port 1679 is not listening."
    die "Check SSH service and backup. Do not close current session."
fi

say "SSH successfully moved to port $SSH_PORT"

say "UFW safe configuration"

ufw allow "${SSH_PORT}/tcp" comment 'SSH port 1679' || true
ufw default deny incoming
ufw default allow outgoing

if ufw status | grep -q 'Status: active'; then
    say "UFW already active. Port 1679 allowed."
else
    say "UFW remains disabled to avoid blocking VPN and panel ports."
fi

say "Final verification"

echo
echo "===== SSH LISTEN ====="
ss -lntp | grep ssh || true

echo
echo "===== SSH CONFIG ====="
sshd -T | grep -E '^(port|pubkeyauthentication|passwordauthentication|permitrootlogin)'

echo
echo "===== SSH SOCKET ====="
systemctl is-active ssh.socket || true

echo
echo "===== SSH SERVICE ====="
systemctl is-active ssh.service || true

echo
echo "===== FAIL2BAN ====="
fail2ban-client status sshd || true

echo
echo "===== TCP CONTROL ====="
sysctl net.ipv4.tcp_congestion_control

echo
echo "===== LIMITS ====="
ulimit -n

echo
echo "===== SWAP ====="
swapon --show || true

echo
echo "===== UFW ====="
ufw status verbose || true

echo
echo "=================================="
echo "VPS OPTIMIZATION COMPLETED"
echo "SSH PORT: $SSH_PORT"
echo "SSH SOCKET: DISABLED"
echo "SSH SERVICE: ENABLED"
echo "BACKUP: $BACKUP"
echo "LOG: $LOG"
echo "=================================="

echo
echo "IMPORTANT:"
echo "Open a second SSH session on port $SSH_PORT."
echo "Verify key authentication before closing the old session."
